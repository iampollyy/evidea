import hashlib
import json
import re
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass, field
from typing import Any, Protocol
from uuid import UUID

SNAPSHOT_SCHEMA_VERSION = 1
DISCLAIMER = "Feature associations, not causal proof."
STUB_NOTICE = "Generated by the EVIDEA demo stub model, not by a trained classifier."


@dataclass(frozen=True)
class LabFeature:
    code: str
    name: str
    unit: str | None
    value: bool | int | float | str


@dataclass(frozen=True)
class Candidate:
    disease_id: UUID
    orpha_code: str
    name: str


@dataclass(frozen=True)
class Explanation:
    method: str
    data: dict[str, Any]
    summary: str | None


@dataclass(frozen=True)
class ScoredDisease:
    disease_id: UUID
    score: float
    explanations: list[Explanation] = field(default_factory=list)


class InferenceModel(Protocol):
    def supports(self, snapshot: Mapping[str, Any]) -> bool: ...

    def predict(
        self, snapshot: Mapping[str, Any], candidates: Sequence[Candidate]
    ) -> list[ScoredDisease]: ...


def build_input_snapshot(
    *,
    anamnesis: Mapping[str, str | None],
    vital_signs: Mapping[str, float | int | None] | None,
    lab_features: Sequence[LabFeature],
    age_years: int,
    sex: str,
) -> dict[str, Any]:
    return {
        "schema_version": SNAPSHOT_SCHEMA_VERSION,
        "text_input": {key: value for key, value in anamnesis.items() if value},
        "lab_input": [asdict(feature) for feature in lab_features],
        "vital_signs": {k: v for k, v in (vital_signs or {}).items() if v is not None},
        "demographics": {"age_years": age_years, "sex": sex},
    }


def _unit_interval(*parts: str) -> float:
    digest = hashlib.sha256("|".join(parts).encode("utf-8")).hexdigest()
    return int(digest[:8], 16) / 0xFFFFFFFF


class StubModel:
    def __init__(self, *, top_k: int = 5) -> None:
        self.top_k = top_k

    def supports(self, snapshot: Mapping[str, Any]) -> bool:
        text = snapshot.get("text_input") or {}
        return bool(isinstance(text, Mapping) and text.get("chief_complaint"))

    def predict(
        self, snapshot: Mapping[str, Any], candidates: Sequence[Candidate]
    ) -> list[ScoredDisease]:
        seed = json.dumps(snapshot, sort_keys=True, default=str)
        raw = sorted(
            (((_unit_interval(seed, c.orpha_code) + 0.05) ** 4, c) for c in candidates),
            key=lambda pair: (-pair[0], pair[1].orpha_code),
        )[: self.top_k]
        total = sum(value for value, _ in raw) or 1.0
        tokens = self._tokens(snapshot)
        labs = [f for f in snapshot.get("lab_input", []) if isinstance(f, Mapping)][:3]
        return [
            ScoredDisease(
                disease_id=candidate.disease_id,
                score=round(value / total, 6),
                explanations=[self._explain(seed, candidate, value / total, tokens, labs)],
            )
            for value, candidate in raw
        ]

    @staticmethod
    def _tokens(snapshot: Mapping[str, Any]) -> list[str]:
        text = snapshot.get("text_input") or {}
        words = re.findall(r"[^\W\d_]{4,}", " ".join(str(v) for v in text.values()).lower())
        return list(dict.fromkeys(words))[:3]

    @staticmethod
    def _explain(
        seed: str,
        candidate: Candidate,
        score: float,
        tokens: Sequence[str],
        labs: Sequence[Mapping[str, Any]],
    ) -> Explanation:
        def contribution(name: str) -> float:
            return round(score * _unit_interval(seed, candidate.orpha_code, name), 4)

        text_features = [{"token": t, "shapValue": contribution(t)} for t in tokens]
        lab_features = [
            {
                "analyte": lab.get("name"),
                "value": lab.get("value"),
                "unit": lab.get("unit"),
                "shapValue": contribution(str(lab.get("code"))),
            }
            for lab in labs
        ]
        top = [str(f["token"]) for f in text_features] + [str(f["analyte"]) for f in lab_features]
        summary = (
            f"Demo explanation for {candidate.name}: largest contributions from "
            + (", ".join(top[:3]) if top else "the overall input")
            + "."
        )
        return Explanation(
            method="shap",
            data={
                "textFeatures": text_features,
                "labFeatures": lab_features,
                "disclaimer": f"{DISCLAIMER} {STUB_NOTICE}",
            },
            summary=summary,
        )
